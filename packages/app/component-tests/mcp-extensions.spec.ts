import { expect, story } from "../../storybook/playwright/story"

story("embeds MCP management and the store in the native extensions tab", async ({ mount, page }) => {
  const component = await mount("settings-mcp--extensions")

  await expect(component.getByRole("heading", { name: "Extensions" })).toBeVisible()
  await expect(component.getByText("Available to all projects")).toBeVisible()
  await expect(component.locator(".settings-extension-name", { hasText: "Local tools" })).toBeVisible()
  await expect(component.getByRole("button", { name: "Add MCP server" })).toBeVisible()
  await expect(component.getByText("Loading", { exact: true })).toBeVisible()
  await expect(component.getByText("Company docs")).toHaveCount(0)
  await component.getByRole("button", { name: "Load MCP catalog" }).click()
  await expect(component.locator(".settings-extension-name", { hasText: "Company search" })).toBeVisible()
  await expect(component.getByRole("heading", { name: "MCP Store" })).toBeVisible()
  await expect(component.getByText("Company docs")).toBeVisible()

  const localSwitch = component.getByRole("switch", { name: "Local tools" })
  await expect(localSwitch).toBeVisible()
  await localSwitch.focus()
  await localSwitch.press("Space")
  await expect(localSwitch).not.toBeChecked()
  await localSwitch.press("Space")
  await expect(localSwitch).toBeChecked()

  await component.getByRole("button", { name: "Add MCP server" }).click()
  const dialog = page.getByRole("dialog")
  await page.evaluate(() => document.fonts.ready.then(() => undefined))
  const bounds = await dialog.boundingBox()
  expect(bounds?.width).toBeGreaterThan(640)
  const inputBounds = await dialog.getByLabel("Name").boundingBox()
  expect(inputBounds!.x - bounds!.x).toBeGreaterThanOrEqual(16)
  await dialog.getByLabel("Name").fill("Fresh MCP")
  await dialog.getByRole("button", { name: "Remote" }).click()
  await dialog.getByLabel("URL").fill("https://mcp.example/fresh")
  await dialog.getByRole("button", { name: "Save", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(component.locator(".settings-extension-name", { hasText: "Fresh MCP" })).toBeVisible()

  const storeDialog = page.getByRole("dialog")
  await component.getByRole("button", { name: "Add", exact: true }).click()
  await page.setViewportSize({ width: 1000, height: 600 })
  await expect(storeDialog.locator("form")).toHaveCSS("overflow-y", "auto")
  const saveBounds = await storeDialog.getByRole("button", { name: "Save", exact: true }).boundingBox()
  expect(saveBounds!.y + saveBounds!.height).toBeLessThanOrEqual(600)
  await storeDialog.getByLabel("Scope", { exact: true }).scrollIntoViewIfNeeded()
  await expect(storeDialog.getByLabel("Scope", { exact: true })).toBeInViewport()
  await expect(storeDialog.getByLabel("Name", { exact: true })).toHaveValue("Company docs")
  await expect(storeDialog.getByLabel("URL")).toHaveValue("https://mcp.example/docs")
  await expect(storeDialog.getByLabel("Header name")).toHaveValue("x-company-token")
  await storeDialog.getByLabel("Header value").fill("company-token")
  await storeDialog.getByRole("button", { name: "Save", exact: true }).click()
  await expect(storeDialog).toHaveCount(0)
  await expect(component.getByRole("switch", { name: "Company docs" })).toBeChecked()

  await component.getByRole("tab", { name: "Plugins" }).click()
  await expect(component.getByText("Storybook plugin")).toBeVisible()
  await expect(component.getByText("Fresh MCP")).toHaveCount(0)
})
